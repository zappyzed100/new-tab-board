// noteHeightEstimate.ts — 未測定ノートの高さを本文から見積もる(masonryの列割当用)
//
// 【なぜ必要か — 2026-07-29】
// 窓化(ViewportNote)は表示領域周辺のノートしかマウントしないため、**大半のノートは高さが
// 未測定**のまま列へ割り当てられる。以前は未測定を一律520pxとして扱っていたが、実際には
// 数千行=数万pxのノートがあり、見積もりが100倍以上ずれていた。列割当がこの見積もりに従って
// 決まる以上、見積もりの粗さがそのまま列バランスの歪みになる。結果、長文ノートを520pxのつもり
// で詰めた列だけが数万px伸び、他の列は先に尽きて「何も無い領域=真っ黒」が数万pxにわたって
// 現れていた(実測: 3列で最大62,825pxの偏り。ユーザー報告の「真っ黒」)。
//
// 完全に当てる必要はない——**列割当が壊滅的に外れない程度に当たれば十分**で、マウント後は
// ResizeObserverの実測値がtopの積み上げ計算(のみ)を置き換える。行数から見積もるだけで
// 桁のズレは消える。
//
// 【割当そのものが見積もりだけに依るのはなぜか — 2026-07-30】
// 列割当は order順(`sortedNotes`順)に「その時点で一番低い列」へ入れる貪欲法(App.tsxの
// `noteLayout`)で、以前のようなスティッキー割当(一度決めたら動かさない)ではない——並べ替え
// 操作(⬆️/⬇️/ドラッグ/ピン)の結果を配置へ反映するため、割当は毎回orderから作り直す。
// しかし割当の入力に実測値(ResizeObserverの値)を混ぜると、窓化の再マウントで高さが
// 未測定→測定済みへ変わるたびに貪欲法の比較結果が変わり、「上スクロール中に列が入れ替わる」
// 不具合が再発する(2026-07-29の回帰・実測1512回/300ステップ)。割当の入力をこの見積もり関数
// だけに限定すれば、内容と列数が同じ限り結果は決定的になり、実測値の有無・タイミングに
// 割当は一切依存しない。
import type { Note } from "../types";

/** ペインの本文以外(見出し・ツールバー・ステータス行・余白)の概算。 */
const CHROME_HEIGHT_PX = 200;
/** CodeMirrorの1行の高さの概算(既定フォントサイズでの実測値に近い値)。 */
const LINE_HEIGHT_PX = 17;
/** 1行に収まる概算文字数。これを超える行は折り返しで複数行ぶんの高さになる。
 * 列幅は画面幅依存だが、桁を合わせるのが目的なので固定の近似で足りる。 */
const CHARS_PER_LINE = 40;
/** 空ノート等でも下回らない下限(ViewportNoteのプレースホルダ既定と揃える)。 */
export const MIN_ESTIMATED_HEIGHT_PX = 520;

/** 本文から描画高さを見積もる。実測値が無いノートの暫定値として使う。 */
export function estimateNoteHeight(note: Pick<Note, "content">): number {
  let rows = 0;
  for (const line of note.content.split("\n")) {
    // 折り返しぶんを数える(空行も1行として数える)。
    rows += Math.max(1, Math.ceil(line.length / CHARS_PER_LINE));
  }
  return Math.max(MIN_ESTIMATED_HEIGHT_PX, CHROME_HEIGHT_PX + rows * LINE_HEIGHT_PX);
}
